def adjust_zero_times(times: np.ndarray, cutoff: float,
                      offset: float = 1e-6) -> None:
    """Adjust `times` so any time where t = 0 is instead set to be `offset`
    before the first nonzero time. This is relevant for datasets where init is
    incorrectly given a timestamp of 0, which causes the init process event to
    occur years before the rest of the dataset. Any time below `cutoff` is
    considered a zero time.

    The default value of `offset` is equivalent to 1us if `times` is an array
    of doubles representing the UNIX epoch in seconds."""
    log.info("adjusting any unrealistically low, if they exist...")
    try:
        low = times[times > cutoff].min()
        times[times <= cutoff] = low - offset
    except ValueError:
        # min failed, so nothing to adjust
        pass

def time_as_str(t: int, tz: datetime.timezone = UTC) -> str:
    """Convert a Unix timestamp to a date string in the given timezone. The
    default timezone is UTC."""
    return datetime.datetime.fromtimestamp(t / 1e9, tz=tz).strftime("%m/%d %H:%M:%S")

def format_timestamp(time: float, tz: datetime.timezone) -> str:
    """Format a floating-point Unix epoch as a date."""
    #return datetime.datetime.fromtimestamp(time, tz=tz).strftime("%Y-%m-%d")
    return datetime.datetime.fromtimestamp(time, tz=tz).strftime("%m-%d")

def make_timestamp_formatter(tz: datetime.timezone) -> Callable:
    """Return a function that can be used as a formatter for matplotlib axes.
    The formatter assumes all times are in the given timezone."""
    return lambda x, pos: format_timestamp(x, tz)

def skip_overwrite(path: str) -> bool:
    """If `path` exists, log a message. Return whether `path` exists."""
    if os.path.exists(path):
        log.warning(f"{path} already exists; refusing to overwrite...")
        return True
    return False

def tc_set_name(tar_dir: str) -> str:
    """Extract the set name from a TC tarball."""
    return tar_dir.rstrip("/").rsplit("/", maxsplit=1)[1].split("-", maxsplit=1)[0]

def pickle_read(path: str) -> Any:
    if path.endswith("xz"):
        opener = lzma.open
    else:
        opener = open
    with opener(path, "rb") as f:
        return pickle.load(f)

def pickle_write(data: Any, path: str) -> None:
    if path.endswith("xz"):
        opener = lzma.open
    else:
        opener = open
    with opener(path, "wb") as f:
        pickle.dump(data, f, protocol=config.pickle_protocol)

def si_binary(size: int, unit: str = "B") -> str:
    """Return `size` as a string represent human-readable binary units."""
    prefixes = ["", "Ki", "Mi", "Gi", "Ti", "Pi", "Ei", "Zi", "Yi"]
    for prefix in prefixes[:-1]:
        if size < 1024.:
            return f"{size:.2f} {prefix}{unit}"
        size /= 1024.
    return f"{size:.2f} {prefixes[-1]}{unit}"

def from_iso8601(timestamp: str) -> np.datetime64:
    """Convert an ISO 8601 Zulu or UTC timestamp (e.g., generated by Windows
    logs) to numpy's datetime64."""
    return np.datetime64(timestamp.rstrip("Z"))

def as_ns(time: np.datetime64) -> int:
    """Convert numpy's datetime64 to a nanosecond timestamp."""
    return time.astype("datetime64[ns]").astype(int)

def to_day(timestamp: float, tz: datetime.timezone) -> datetime.datetime:
    """Return a datetime of `timestamp` truncated to the nearest day."""
    dt = datetime.datetime.fromtimestamp(timestamp, tz=tz)
    return datetime.datetime(dt.year, dt.month, dt.day, tzinfo=tz)

def xaxis_format_dates(fig, ax, *, step=1, tz=UTC) -> None:
    """Set matplotlib `fig` and `ax` to display float timestamps as dates,
    with a tick every `step` days. Displays timezones as belonging to `tz`."""

    #def format_optc_timestamp(x: float, pos) -> str:
    #    """Format a floating-point Unix epoch as a date."""
    #    return datetime.datetime.fromtimestamp(x).strftime("%Y-%m-%d %H:%M")

    ax.xaxis.set_major_formatter(make_timestamp_formatter(tz))
    # mdates doesn't work with epoch timestamps
    ax.autoscale(enable=True, tight=True, axis="x")
    start, end = ax.get_xlim()
    # adjust start and end to the nearest day
    start = to_day(start, tz).timestamp()
    end = (to_day(end, tz) + datetime.timedelta(days=1)).timestamp()

    ax.set_xticks(np.arange(start, end, step * 86400))
    ax.set_xlim(start, end)
    fig.autofmt_xdate()
