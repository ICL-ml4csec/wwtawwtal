"""Try to get hostnames of IP addresses within a log. This also saves the
intermediate mapping used, as the results of reverse lookups can change over
time."""

import json
import logging
import lzma
import socket
from typing import Optional, Tuple

import igraph as ig

import config
import util

log = logging.getLogger(__name__)

def reverse(addr: str) -> Tuple[str, str]:
    """Given a socket address, e.g., "72.32.153.176", return the corresponding
    hostname if found, else return the input address."""
    # use port 0: port is not important
    try:
        revname, _ = socket.getnameinfo((addr, 0), 0)
        return revname
    except socket.gaierror:
        return addr

def addr_from_sockname(name: str) -> Optional[str]:
    """Return just the IP address from a graph node name for a socket."""
    addr = name[5:]
    # assume IPv4 addresses
    try:
        addr, _ = addr.rsplit(":", maxsplit=1)
        return addr
    except:
        log.warning("warning: unrecognized address %s", addr)
        return None


def reverse_sockets(cfg, set_name: str, g: ig.Graph) -> None:
    """Write the reverse mapping as a JSON-formatted intermediate dict."""
    log.info("doing reverse lookups...")
    # grab everything that looks like a socket
    d = {}
    for name in g.vs(lambda u: u["name"].startswith("sock="))["name"]:
        addr = addr_from_sockname(name)
        if addr is not None and addr not in d:
            revname = reverse(addr)
            d[addr] = revname

    out_path = f"{cfg.addresses}/{set_name}.json.xz"
    log.info("writing results to %s...", out_path)
    with lzma.open(out_path, "wt") as f:
        json.dump(d, f, sort_keys=True, indent=2)

def rename_sockets(cfg, set_name: str, g: ig.Graph):
    """Rename graph sockets based on the mapping generated by
    `reverse_sockets`.

    Instead of using the official list maintained by ICANN found here:

    https://data.iana.org/TLD/tlds-alpha-by-domain.txt

    this uses a manually curated list of valid TLDs. Unfortunately, the list
    of TLDs contains many names that are also common domains themselves (e.g.,
    health is a valid TLD, but health.mil is a domain that appears in CADETS).
    We also have the issue of SLDs, so just removing the rightmost name would
    falsely group together everything in the same SLD. Therefore, we try to
    detect SLDs by looking for "common" SLDs.
    """
    # TMP: treat all sockets as the same
    #for u in g.vs(lambda u: u["name"].startswith("sock=")):
    #    u["name"] = "sock=skt"
    #return

    # per-domain code below
    slds = {"ac", "co", "com", "ne", "net", "or", "org"}

    log.info("reading socket mapping...")
    mapping_path = f"{cfg.addresses}/{set_name}.json.xz"
    with lzma.open(mapping_path, "rt") as f:
        mapping = json.load(f)

    log.info("truncating to domain names only...")
    for k, v in mapping.items():
        # treat all failed reverse lookups as the same
        if k == v:
            #mapping[k] = "sock=?"
            mapping[k] = f"sock={k}"
            continue
        # assume reversed names are always valid, so rightmost is always a TLD
        tokens = v.rsplit(".", maxsplit=4)
        # (unless it happens to be localhost)
        if len(tokens) == 1:
            assert v == "localhost"
            continue
        # check if 2nd is a SLD:
        if tokens[-2] in slds:
            domain = ".".join(tokens[-3:])
        else:
            domain = ".".join(tokens[-2:])
        mapping[k] = f"sock={domain}"

    log.info("rewriting graph socket names...")
    for u in g.vs(lambda u: u["name"].startswith("sock=")):
        addr = addr_from_sockname(u["name"])
        if addr is None:
            continue
        u["name"] = mapping[addr]


def main(argv):
    for cfg, sets in [
            #(config.e3, ["cadets", "theia", "fivedirections", "trace"]),
            #(config.atlasv2, ["h1", "h2"]),
            (config.streamspot, ["all"]),
        ]:
        for set_name in sets:
            graph_path = f"{cfg.graphs}/{set_name}_prov_graph.pkl.xz"
            log.info("reading graph from %s", graph_path)
            g = util.pickle_read(graph_path)
            if cfg == config.streamspot:
                g = g.g
            reverse_sockets(cfg, set_name, g)
